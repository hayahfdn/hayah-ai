"""Database models. PostgreSQL is the single source of truth.

Design rules enforced here and in the services layer:
- `projects.well_id` is unique and never generated by AI.
- History tables (project_events, audit_log, maintenance_records,
  delivery_confirmations, inbound_messages, media_assets) are append-only in
  practice: rows are never deleted by the application.
- Every externally triggered write carries an idempotency key.
"""
