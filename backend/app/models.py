from app.db import Base


def utcnow() -> datetime:
    return datetime.now(timezone.utc)


def _enum(e: type[enum.Enum], name: str):
    return Enum(e, name=name, values_callable=lambda x: [m.value for m in x], native_enum=False, length=40)


